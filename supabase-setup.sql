create table if not exists public.memories (
  id bigint generated by default as identity primary key,
  title text not null default '',
  description text not null default '',
  location text not null default '',
  taken_at date,
  created_by text not null default '',
  storage_path text not null,
  created_at timestamptz not null default now()
);

alter table public.memories enable row level security;

drop policy if exists "Anyone can view memories" on public.memories;
create policy "Anyone can view memories" on public.memories
  for select to anon using (true);

drop policy if exists "Anyone can add memories" on public.memories;
create policy "Anyone can add memories" on public.memories
  for insert to anon with check (true);

grant select, insert on public.memories to anon;
grant delete on public.memories to anon;
grant usage, select on sequence public.memories_id_seq to anon;

drop policy if exists "Anyone can delete memories" on public.memories;
create policy "Anyone can delete memories" on public.memories
  for delete to anon using (true);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('album-fotos', 'album-fotos', true, 10485760,
  array['image/jpeg','image/png','image/gif','image/webp'])
on conflict (id) do update set public = true;

